#include <stdio.h>

int main() {

	double m[9], r3[9], n[9];

	for (int i = 0; i < 9; i++) {
		scanf("%lf", &m[i]);
	}

	for (int i = 0; i < 9; i++) {
		scanf("%lf", &n[i]);
	}

	r3[0] = (m[0] * n[0]) + (m[1] * n[3]) + (m[2] * n[6]);
	r3[1] = (m[0] * n[1]) + (m[1] * n[4]) + (m[2] * n[7]);
	r3[2] = (m[0] * n[2]) + (m[1] * n[5]) + (m[2] * n[8]);
	
	r3[3] = (m[3] * n[0]) + (m[4] * n[3]) + (m[5] * n[6]);
	r3[4] = (m[3] * n[1]) + (m[4] * n[4]) + (m[5] * n[7]);
	r3[5] = (m[3] * n[2]) + (m[4] * n[5]) + (m[5] * n[8]);
	
	r3[6] = (m[6] * n[0]) + (m[7] * n[3]) + (m[8] * n[6]);
	r3[7] = (m[6] * n[1]) + (m[7] * n[4]) + (m[8] * n[7]);
	r3[8] = (m[6] * n[2]) + (m[7] * n[5]) + (m[8] * n[8]);
	

	printf("A x B\n%.2f %.2f %.2f\n%.2f %.2f %.2f\n%.2f %.2f %.2f", 
			r3[0], r3[1], r3[2], 
			r3[3], r3[4], r3[5], 
			r3[6], r3[7], r3[8] );
	return 0;
}